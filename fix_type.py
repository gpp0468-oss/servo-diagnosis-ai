import re

FIX_TYPES = ["换件", "参数调整", "接线整改", "程序与逻辑", "机械整改", "规避降级", "人工判断"]

RULES = [
    ("换件", ["更换", "替换", "返修", "返厂", "换新", "换一台", "更换伺服", "更换电机"]),
    ("规避降级", ["降速", "降额", "限速", "规避", "减小速度", "降低速度", "降低负载", "降低增益上限"]),
    ("程序与逻辑", ["程序", "上位机", "PLC", "逻辑", "时序", "主站", "控制字", "模式切换"]),
    ("接线整改", ["接线", "线缆", "屏蔽", "接地", "插头", "端子", "紧固", "布线", "重新插"]),
    ("机械整改", ["联轴器", "皮带", "丝杠", "减速箱", "导轨", "轴承", "闸片", "气隙", "抱闸机械"]),
    ("参数调整", ["参数", "设置", "设定", "调整", "整定", "修改", "增益", "惯量", "齿轮比",
                  "刚性", "滤波", "限幅", "使能"]),
]


def classify_fix(action: str) -> str:
    a = action or ""
    for name, keys in RULES:
        if any(k in a for k in keys):
            return name
    return "人工判断"
